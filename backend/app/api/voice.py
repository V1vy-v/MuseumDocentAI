# 【角色 D 负责】语音问答接口（占位骨架）
#
# POST /api/voice
#   请求：录音文件（音频）+ 会话编号
#   响应：{ answer: 回答文本, sources: [资料来源], audio: 回答音频(可选) }
#
# 与文本接口的区别：mimo-v2.5-asr 支持语音直接输入，
# 录音不用先转文字，直接把音频交给模型"听"（封装在 llm_client.py）。
#
# 处理流程：
#   1. 接收音频文件（格式待确认：WAV/PCM/MP3？）
#   2. 音频 + 对话历史 + RAG 检索到的资料 → 交给 mimo-v2.5-asr
#   3. 拿到回答文本 → 需要播报时再合成语音（tts_client.py，视模型能力启用）
#   4. 返回给 APP
