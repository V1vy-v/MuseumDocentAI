# 【防幻觉】本馆具体信息类问题识别
#
# 为什么需要它：提示词里已经明确写了"开放时间、门票、展厅分布都属于馆内信息，
# 资料未收录就不要编造"，但实测——「博物馆开放时间？」被拦住了，
# 「有哪些展厅？」模型照样编出了"人之源/城之源/金色中国"（那是别的馆的展厅）。
#
# 结论：靠提示词约束模型不编造，只对一部分问法有效，不能当作底线。
# 所以对【风险最高、最容易编、又最容易被观众当场发现】的那类问题，
# 用确定性规则短路：馆内没有资料 + 问的是本馆具体信息 → 直接回固定话术。
#
# 这样做的代价是可能误拦（观众其实问的是馆外的通识问题），
# 所以关键词收得比较窄，只收"一定是在问这座馆本身"的说法。

import re

_VENUE_FACTS = (
    # 开放与票务
    "开放时间", "几点开", "几点关", "几点到", "闭馆", "开馆",
    "门票", "票价", "多少钱一张", "买票", "预约", "免票", "学生票",
    # 位置与交通
    "地址", "怎么去", "怎么走", "地铁路线", "公交", "停车", "导航",
    # 馆内服务
    "电话", "咨询电话", "讲解服务", "讲解员预约", "轮椅", "寄存", "厕所",
    "餐厅", "吃饭", "文创", "纪念品", "商店", "导览图",
    # 展厅与路线（本馆的展览布局）
    "有哪些展厅", "几个展厅", "展厅分布", "参观路线", "游览路线", "参观顺序",
)

_ZH = re.compile(r"[\u4e00-\u9fff]")


def is_venue_fact(question: str) -> bool:
    """这句话是不是在问"这座馆的具体信息"（时间/票/位置/服务/展厅布局）

    只对**馆内具体信息**成立。问文物本身、问历史背景都不算——
    那些应该走正常回答流程。
    """
    text = (question or "").strip()
    if not text or not _ZH.search(text):
        return False
    return any(word in text for word in _VENUE_FACTS)
